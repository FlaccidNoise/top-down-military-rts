// MainMenu shell (Strategic Layer V2 §9). Shell only: this module owns
// rendering and callbacks, nothing else. The real save probe (S37) and the
// mode-machine wiring (S2) plug in later through setSaveProbe/the cb object.

export type SaveProbeStatus = 'none' | 'legacy' | 'stale-generator' | 'corrupt' | 'ok';

export interface SaveProbe {
  status: SaveProbeStatus;
  detail?: string;       // corrupt: what went wrong
  day?: number;           // ok
  clock?: string;         // ok — pre-formatted, e.g. "14:32"
  theaterName?: string;   // ok
  menFit?: number;        // ok
}

export interface MainMenuCallbacks {
  onNewOperation(): void;
  onContinue(): void;
  onContinueLegacy(): void;
  onDiscardSave(): void;
  onFieldManual(): void;
  // The tutorial switch lives HERE and not only in the pause menu because
  // turning it back on has to happen BEFORE the operation starts: the briefing
  // card fires on campaign-start, so a player who re-enables mid-campaign
  // would miss the one step that explains the goal. Absent (?camp= art path)
  // = no tutorial exists, and the control does not render.
  tutorialEnabled?(): boolean;
  onTutorialToggle?(on: boolean): void;
}

// Save-file strings (detail, clock, theaterName) reach innerHTML; a corrupt
// save is hostile input and must reject visibly WITHOUT executing.
export function esc(s: string): string {
  return s.replace(/[&<>"']/g, (c) => `&#${c.charCodeAt(0)};`);
}

const CONTINUE_ID = 'mm-continue';
const CONTINUE_LEGACY_ID = 'mm-continue-legacy';
const DISCARD_ID = 'mm-discard';
const NEW_OP_ID = 'mm-new';
const MANUAL_ID = 'mm-manual';
const TUTORIAL_ID = 'mm-tutorial';

// Pure — no DOM globals, so the five states are testable without a browser.
export function renderContinueBlock(probe: SaveProbe): string {
  switch (probe.status) {
    case 'none':
      return `<div class="mm-continue">
        <button id="${CONTINUE_ID}" class="primary" disabled title="No saved campaign">Continue</button>
        <p class="mm-reason">No saved campaign.</p>
      </div>`;
    case 'legacy':
      return `<div class="mm-continue">
        <p class="mm-msg">This save is from an earlier campaign format. Your men can carry over to a new theater.</p>
        <div class="mm-continue-actions">
          <button id="${CONTINUE_LEGACY_ID}" class="primary">Continue with these men</button>
          <button id="${DISCARD_ID}">Discard</button>
        </div>
      </div>`;
    case 'stale-generator':
      return `<div class="mm-continue">
        <p class="mm-msg">Generated by an older map generator — cannot be reproduced.</p>
        <div class="mm-continue-actions">
          <button id="${DISCARD_ID}">Discard</button>
        </div>
      </div>`;
    case 'corrupt':
      return `<div class="mm-continue">
        <p class="mm-msg">Save is corrupt${probe.detail ? `: ${esc(probe.detail)}` : '.'}</p>
        <div class="mm-continue-actions">
          <button id="${DISCARD_ID}">Discard</button>
        </div>
      </div>`;
    case 'ok':
      return `<div class="mm-continue">
        <button id="${CONTINUE_ID}" class="primary">Continue</button>
        <p class="mm-status">Day ${probe.day} · ${esc(probe.clock ?? '')} · ${esc(probe.theaterName ?? '')} · ${probe.menFit} fit</p>
      </div>`;
  }
}

// Pure — persistent "progress is not being saved" banner (§7's saveGame
// failure badge, shown from boot when storage already can't be probed).
export function renderStorageBanner(writable: boolean): string {
  if (writable) return '';
  return `<div id="mm-storage-banner">Progress is not being saved` +
    `<small>Storage is unavailable — private browsing or a full quota.</small></div>`;
}

export class MainMenu {
  private el: HTMLDivElement;
  private cb: MainMenuCallbacks;
  private probe: SaveProbe = { status: 'none' };
  private storageWritable = true;
  private _open = false;

  constructor(cb: MainMenuCallbacks) {
    this.cb = cb;
    this.el = document.createElement('div');
    this.el.id = 'mainmenu';
    this.el.style.display = 'none';
    document.body.appendChild(this.el);
  }

  get isOpen(): boolean { return this._open; }

  setSaveProbe(probe: SaveProbe): void {
    this.probe = probe;
    if (this._open) this.render();
  }

  setStorageWritable(writable: boolean): void {
    this.storageWritable = writable;
    if (this._open) this.render();
  }

  open(): void {
    this._open = true;
    this.render();
    this.el.style.display = 'flex';
  }

  close(): void {
    this._open = false;
    this.el.style.display = 'none';
  }

  private render(): void {
    this.el.innerHTML = `${renderStorageBanner(this.storageWritable)}<div class="db-scroll"><div class="db"><div class="mm-panel">
      <h1>NORMANDY</h1>
      ${renderContinueBlock(this.probe)}
    </div></div></div>
    <div class="db-actions">
      <button id="${NEW_OP_ID}" class="primary">New Operation</button>
      <button id="${MANUAL_ID}">Field Manual</button>
      ${this.cb.tutorialEnabled ? `<button id="${TUTORIAL_ID}" aria-pressed="${this.cb.tutorialEnabled()}">Tutorial: ${this.cb.tutorialEnabled() ? 'ON' : 'OFF'}</button>` : ''}
    </div>`;

    this.el.querySelector(`#${NEW_OP_ID}`)?.addEventListener('click', () => this.cb.onNewOperation());
    this.el.querySelector(`#${MANUAL_ID}`)?.addEventListener('click', () => this.cb.onFieldManual());
    this.el.querySelector(`#${TUTORIAL_ID}`)?.addEventListener('click', () => {
      this.cb.onTutorialToggle?.(!this.cb.tutorialEnabled!());
      this.render(); // the label IS the state
    });
    this.el.querySelector(`#${CONTINUE_ID}`)?.addEventListener('click', () => this.cb.onContinue());
    this.el.querySelector(`#${CONTINUE_LEGACY_ID}`)?.addEventListener('click', () => this.cb.onContinueLegacy());
    this.el.querySelector(`#${DISCARD_ID}`)?.addEventListener('click', () => this.cb.onDiscardSave());
  }
}
